DFLASH_TEST="$PACKAGE_ROOT/Tests/ModelQuantizerTests/DFlashScaleSearchConversionTests.swift"
MIXTRAL_FIXTURE="$PACKAGE_ROOT/Tests/Fixtures/MixtralTiny/config.json"
MISTRAL_FIXTURE="$PACKAGE_ROOT/Tests/Fixtures/MistralTiny/config.json"
GPT_OSS_FIXTURE="$PACKAGE_ROOT/Tests/Fixtures/GPTOSSTiny/config.json"
DFLASH_FIXTURE="$PACKAGE_ROOT/Tests/Fixtures/LagunaDFlashTiny/config.json"

grep -Fq 'name: "wick"' "$PACKAGE"
grep -Fq 'name: "facet"' "$PACKAGE"
grep -Fq 'name: "model-runner-quantize"' "$PACKAGE"
grep -Fq 'name: "ModelQuantizerTests"' "$PACKAGE"
grep -Fq 'wick|facet|model-runner-quantize' "$PACKAGE_ROOT/build.sh"
grep -Fq 'wick-laguna-quantize|model-runner-laguna-quantize' "$PACKAGE_ROOT/build.sh"
grep -Fq 'LLMTypeRegistry.shared.createModel' "$QUANTIZER"
grep -Fq 'LLMModelFactory.shared.convert' "$QUANTIZER"
grep -Fq 'name: .customLong("standard-q4")' "$QUANTIZER"
grep -Fq 'calibration: recipe.mlxCalibration' "$QUANTIZER"
grep -Fq 'recipe.mode.rawValue' "$QUANTIZER"
grep -Fq 'standard-q4-quantization.json' "$QUANTIZER"
grep -Fq 'scale-search-quantization.json' "$QUANTIZER"
grep -Fq 'plan.scaleSearchPaths.union(plan.standardQ4Paths).sorted()' "$QUANTIZER"
grep -Fq 'name: .customLong("group-size")' "$QUANTIZER"
