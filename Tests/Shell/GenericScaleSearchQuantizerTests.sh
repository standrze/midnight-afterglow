set -euo pipefail

PACKAGE_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PACKAGE="$PACKAGE_ROOT/Package.swift"
QUANTIZER="$PACKAGE_ROOT/Sources/ModelQuantizer/main.swift"
RESCORER="$PACKAGE_ROOT/Sources/LagunaScaleSearchRescorer/LagunaScaleSearchRescorer.swift"
RESCORER_CLI="$PACKAGE_ROOT/Sources/LagunaScaleSearchRescorerCLI/main.swift"
