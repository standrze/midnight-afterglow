grep -Fq 'activationStats == nil || (groupSize == 64 && recipe.usesScaleSearch)' "$QUANTIZER"
grep -Fq 'groupSize: groupSize,' "$QUANTIZER"
grep -Fq 'standardQ4: standardQ4,' "$QUANTIZER"
grep -Fq 'mlx-swift-lm-q4-affine-group-size.patch' "$PACKAGE_ROOT/prepare-dependencies.sh"
grep -Fq 'groupSize: Int = 64' "$PACKAGE_ROOT/Patches/mlx-swift-lm-q4-affine-group-size.patch"
grep -Fq 'module is Linear || module is SwitchLinear' "$QUANTIZER"
grep -Fq '.block_sparse_moe.gate' "$QUANTIZER"
grep -Fq '.mlp.router' "$QUANTIZER"
grep -Fq '.mlp.gate.proj' "$QUANTIZER"
grep -Fq 'DFlashLagunaForCausalLM' "$QUANTIZER"
grep -Fq 'MTPDrafterTypeRegistry.shared.createModel' "$QUANTIZER"
grep -Fq 'MLXLMCommon.convert' "$QUANTIZER"
grep -Fq 'mandatoryQ8Suffixes: ["fc", ".self_attn.g_proj"]' "$QUANTIZER"
grep -Fq 'mandatory Q8 module(s) cannot be skipped' "$QUANTIZER"
grep -Fq 'LagunaScaleSearchRescorer.rescore' "$QUANTIZER"
grep -Fq 'public struct LagunaScaleSearchRescorer' "$RESCORER"
grep -Fq 'LagunaScaleSearchRescorer.main()' "$RESCORER_CLI"
grep -Fq 'public enum LagunaModelRegistration' "$LAGUNA_MODEL"
grep -Fq 'public enum LagunaDFlashRegistration' "$DFLASH_MODEL"
grep -Fq 'block_sparse_moe.switch_mlp.gate_proj.scales' "$MIXTRAL_TEST"
grep -Fq 'routerQuantization.bits, 8' "$MIXTRAL_TEST"
grep -Fq 'calibration: .standard' "$MIXTRAL_TEST"
grep -Fq 'XCTAssertEqual(Set(outputArrays.keys), Set(standardArrays.keys))' "$MIXTRAL_TEST"
grep -Fq 'testDFlashFusedCheckpointConvertsAndReloads' "$DFLASH_TEST"
grep -Fq 'MTPDrafterTypeRegistry.shared.createModel' "$DFLASH_TEST"
grep -Fq 'gate_up_proj.scales' "$DFLASH_TEST"
grep -Fq '"model_type": "mixtral"' "$MIXTRAL_FIXTURE"
grep -Fq '"model_type": "mistral"' "$MISTRAL_FIXTURE"
grep -Fq '"model_type": "gpt_oss"' "$GPT_OSS_FIXTURE"
grep -Fq '"DFlashLagunaForCausalLM"' "$DFLASH_FIXTURE"
test ! -e "$PACKAGE_ROOT/Sources/LagunaScaleSearchRescorer/main.swift"

echo "Generic Swift ScaleSearch quantizer checks passed"
